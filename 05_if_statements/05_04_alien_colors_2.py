# more code about alien colors and if statements, this time with an if-else statement

alien_color = 'green'
if alien_color == 'green':
    print("You just earned 5 points for shooting the alien!")
else:
    print("You just earned 10 points!")
alien_color = 'red'
if alien_color != 'green':
    print("You just earned 10 points for shooting the other alien!")
else:
    print("You just earned 10 points")