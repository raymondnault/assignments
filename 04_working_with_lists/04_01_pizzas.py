# this loop will print my favorite pizzas and a message of thanks for sharing my preferences

pizzas = ['pepperoni', 'cheese', 'buffalo chicken']
for pizza in pizzas:
    print(f"I like {pizza} pizza.")
    print(f"{pizza} pizza is my favorite!")

    print('Thank you for letting me share my favorite pizzas!')