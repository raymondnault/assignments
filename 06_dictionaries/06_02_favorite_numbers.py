print('Alice: {}'.format(favorite_numbers['Alice']))
print('Bob: {}'.format(favorite_numbers['Bob']))
print('Nicole: {}'.format(favorite_numbers['Nicole']))
print('John: {}'.format(favorite_numbers['John']))
